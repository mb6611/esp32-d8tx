"""Re-run every golden vector and capture in protocol/ through the Python package (the reference implementation).

The vectors are generated by python/tools/gen_vectors.py; these tests fail if the package and the committed files
disagree (regenerate with `python python/tools/gen_vectors.py` after an intended change)."""
import json
import os
import sys
import zlib

import numpy as np
import pytest

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
VEC = os.path.join(ROOT, "protocol", "vectors")
CAPS = os.path.join(ROOT, "protocol", "captures")
sys.path.insert(0, os.path.join(ROOT, "python", "tools"))

import gen_vectors as G  # noqa: E402
from d8tx.link import unpack4  # noqa: E402
from d8tx.telemetry import decode_capture, load_iq, payload_ok  # noqa: E402


def load(name):
    with open(os.path.join(VEC, name)) as f:
        return json.load(f)


def same(obj):
    return json.loads(json.dumps(obj))


@pytest.mark.parametrize("name,build", [
    ("commands.json", G.commands), ("replies.json", G.replies), ("reader.json", G.reader),
    ("tlm_header.json", G.tlm_header), ("unpack4.json", G.unpack4_vectors), ("tid_rule.json", G.tid_rule),
    ("hub.json", G.hub), ("reply_parse.json", G.reply_cases), ("tracker.json", G.tracker), ("msp.json", G.msp),
])
def test_vector_file_matches_package(name, build):
    assert same(build()) == load(name)


def test_commands_header_is_current():
    path = os.path.join(VEC, "commands.h")
    old = open(path, "rb").read()
    try:
        G.write_commands_h(load("commands.json"))
        assert open(path, "rb").read() == old
    finally:
        open(path, "wb").write(old)


def test_unpack4_vectors_independent():
    for c in load("unpack4.json"):
        p = bytes.fromhex(c["payload"])
        want = bytearray()
        for b in p:
            for nib in (b & 0xF, b >> 4):
                want.append((nib - 16 if nib >= 8 else nib) & 0xFF)
        assert unpack4(p) == bytes(want) == bytes.fromhex(c["iq8"])


INDEX = json.load(open(os.path.join(CAPS, "index.json")))


def test_captures_total_size():
    total = sum(os.path.getsize(os.path.join(CAPS, e["file"])) for e in INDEX)
    assert total < 200 * 1024


@pytest.mark.parametrize("e", INDEX, ids=[e["file"] for e in INDEX])
def test_capture_decodes_as_indexed(e):
    payload = open(os.path.join(CAPS, e["file"]), "rb").read()
    assert payload_ok({"bytes": e["bytes"], "crc": e["crc"]}, payload)
    assert zlib.crc32(payload) & 0xFFFFFFFF == int(e["crc"], 16)
    p, bits = (unpack4(payload), 8) if e["bits"] == 4 else (payload, e["bits"])
    r = decode_capture(load_iq(p, e["n"], bits), e["fs"])
    if e["expect"] is None:
        assert r is None
        return
    x = e["expect"]
    assert r is not None
    assert (r["a1"], r["a2"], r["rssi"], r["tid"], r["hub_count"]) == (x["a1"], x["a2"], x["rssi"], x["tid"], x["hub_count"])
    assert r["hub"].hex() == x["hub"]
    assert abs(r["cfo_hz"] - x["cfo_hz"]) < 1.0


def test_every_real_capture_decodes_in_both_formats():
    real = [e for e in INDEX if "noise" not in e["file"]]
    assert len(real) == 12 and all(e["expect"] is not None for e in real)
    assert sum(e["format"] == "i4_d64" for e in INDEX) == 7
    noise = [e for e in INDEX if "noise" in e["file"]]
    assert len(noise) == 2 and all(e["expect"] is None for e in noise)
