#!/usr/bin/env python3
"""Append/refresh the TX chapter (from tx.md, via pandoc) inside index.html.

Only the region between the BEGIN/END markers is owned by this script; it is
inserted before </main> on first run and replaced on re-runs (idempotent).
Also removes the obsolete tx.html cross-link and adds one figcaption CSS rule.
"""
import html, pathlib, re, subprocess
d = pathlib.Path(__file__).resolve().parent
BEGIN, END = "<!-- BEGIN TX CHAPTER (generated by render_tx.py from tx.md; do not edit) -->", "<!-- END TX CHAPTER -->"
md = (d / "tx.md").read_text()
title = re.match(r"# (.+)", md).group(1)
md = re.sub(r"^# .+\n", "", md, count=1)
md = re.sub(r"\[([^\]]+)\]\(README\.md\)", r"\1 above", md)  # no cross-page link: same document
md = md.replace("companion to the RX write-up, A 2.4 GHz SDR on a $5 ESP32 above", "continuing the RX write-up above")
body = subprocess.run(["pandoc", "-f", "markdown", "-t", "html", "--no-highlight", "--wrap=none"],
                      input=md, capture_output=True, text=True, check=True).stdout
body = re.sub(r"<colgroup>.*?</colgroup>\s*", "", body, flags=re.S)
body = re.sub(r"<table>.*?</table>", lambda m: '<div class="tw">' + m.group(0) + "</div>", body, flags=re.S)
body = re.sub(r'(<figure>\s*)(<img [^>]*src="([^"]+)"[^>]*>)', lambda m: f'{m.group(1)}<a href="{m.group(3)}">{m.group(2).replace("<img ", "<img loading=\"lazy\" ", 1)}</a>', body)
body = re.sub(r"(<figure>.*?)<figcaption[^>]*>.*?</figcaption>\s*</figure>\s*<p><em>(Figure .*?)</em></p>",
              r"\1<figcaption>\2</figcaption>\n</figure>", body, flags=re.S)
m = re.match(r"\s*<p><em>(.*?)</em></p>", body, re.S)
by, body = m.group(1), body[m.end():]
chapter = f"""{BEGIN}
<hr>
<p><em>The write-up above is the receive story as it stood when it was written: a board that could only listen. What follows is a later, separate result from the transmit branch of the project: the same chip transmitting, from one packet to the whole FrSky D8 protocol.</em></p>
<h2 id="tx-chapter">{html.escape(title)}</h2>
<p class="by"><em>{by}</em></p>
{body.rstrip()}
{END}
"""
p = d / "index.html"
idx = p.read_text()
idx = re.sub(r' · <a href="tx\.html">[^<]*</a>', "", idx)
if "figcaption a{display:inline}" not in idx:
    idx = idx.replace("</style>", "figcaption a{display:inline}\n</style>", 1)
if BEGIN in idx:
    idx = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END) + r"\n", lambda _: chapter, idx, flags=re.S)
else:
    idx = idx.replace("\n</main>", "\n" + chapter + "</main>", 1)
p.write_text(idx)
